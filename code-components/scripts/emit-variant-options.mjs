// Emits src/webflow-components/variant-options.json:
//   component name → variant prop (Designer name) → { default, options }
//
// It EXECUTES the *.webflow.tsx declarations (with @webflow/* stubbed), so
// option lists produced by tokenOptions()/generated arrays are resolved from
// the real code — the JSON can never drift from what actually ships.
//
// Regenerate: npm run variants   (or node scripts/emit-variant-options.mjs)
import { build } from "esbuild";
import { readdirSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const declDir = join(root, "src", "webflow-components");
const outFile = join(declDir, "variant-options.json");

const files = readdirSync(declDir).filter((f) => f.endsWith(".webflow.tsx"));

const entry = [
  ...files.map((f, i) => `import D${i} from "./src/webflow-components/${f}";`),
  `export default { ${files.map((f, i) => `"${f}": D${i}`).join(", ")} };`,
].join("\n");

const STUBS = {
  "wf-react": `
    export const declareComponent = (component, config) => ({ __declaration: config });
    export const useFunction = () => () => Promise.resolve(null);
    export const useSuspenseData = () => ({ data: undefined });
  `,
  "wf-data-types": `
    const make = (type) => (opts) => ({ __type: type, ...(opts || {}) });
    export const props = new Proxy({}, { get: (_, key) => make(String(key)) });
  `,
  "wf-functions": `export const declareFunction = (fn) => fn;`,
};

const stubPlugin = {
  name: "webflow-stubs",
  setup(b) {
    b.onResolve({ filter: /^@webflow\/react$/ }, () => ({ path: "wf-react", namespace: "stub" }));
    b.onResolve({ filter: /^@webflow\/data-types$/ }, () => ({ path: "wf-data-types", namespace: "stub" }));
    b.onResolve({ filter: /^@webflow\/functions$/ }, () => ({ path: "wf-functions", namespace: "stub" }));
    b.onLoad({ filter: /.*/, namespace: "stub" }, (args) => ({ contents: STUBS[args.path], loader: "js" }));
  },
};

const tmp = mkdtempSync(join(tmpdir(), "wf-variants-"));
const bundle = join(tmp, "declarations.mjs");

await build({
  stdin: { contents: entry, resolveDir: root, loader: "ts" },
  bundle: true,
  format: "esm",
  platform: "node",
  outfile: bundle,
  jsx: "automatic",
  logLevel: "error",
  plugins: [stubPlugin],
});

const { default: modules } = await import(pathToFileURL(bundle).href);
rmSync(tmp, { recursive: true, force: true });

const out = {
  "//": "GENERATED by scripts/emit-variant-options.mjs from the *.webflow.tsx declarations - regenerate with `npm run variants`, never hand-edit",
};

if (process.env.DEBUG_VARIANTS) {
  for (const [f, m] of Object.entries(modules)) {
    console.error(f, "→", m && typeof m, m && JSON.stringify(Object.keys(m)), m?.__declaration?.group);
  }
}

const entries = Object.entries(modules)
  .map(([file, mod]) => ({ file, cfg: mod?.__declaration }))
  .filter(({ cfg }) => cfg?.group === "Harvey v3")
  .sort((a, b) => a.cfg.name.localeCompare(b.cfg.name));

for (const { cfg } of entries) {
  const component = {};
  for (const prop of Object.values(cfg.props ?? {})) {
    if (prop?.__type !== "Variant") continue;
    component[prop.name] = {
      default: prop.defaultValue ?? prop.options?.[0],
      options: prop.options ?? [],
    };
  }
  out[cfg.name] = component;
}

writeFileSync(outFile, JSON.stringify(out, null, 2) + "\n");
const count = entries.length;
const propCount = entries.reduce(
  (n, { cfg }) => n + Object.values(cfg.props ?? {}).filter((p) => p?.__type === "Variant").length,
  0,
);
console.log(`Wrote ${outFile}: ${count} components, ${propCount} variant props`);
